class StaffMember {
  final String id;
  final String name;
  final String employeeId;
  final String role;
  final String phone;
  final String email;
  final DateTime joiningDate;
  final String status;

  const StaffMember({
    required this.id,
    required this.name,
    required this.employeeId,
    required this.role,
    required this.phone,
    required this.email,
    required this.joiningDate,
    required this.status,
  });
}
